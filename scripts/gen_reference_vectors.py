"""Run the two reference pools over their plans and write what they answered into
`src/reference_vectors_wbtest.mbt`.

    python3 scripts/gen_reference_vectors.py

The plans beside the reference scripts say which steps to run and when; each script
drives its own pool and prints the answers. This file turns both recordings into
MoonBit data, so `moon test` replays them against moonpool on every target without
either reference installed. The output is committed; CI regenerates it and fails
when the tree differs, which is what ties the data to the references. The file is
formatted afterwards, so what the script writes and what the tree holds are the same
thing only after `moon fmt` has run -- which this script does itself.
"""

import argparse
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REFERENCE = ROOT / "scripts" / "reference"
OUT = ROOT / "src" / "reference_vectors_wbtest.mbt"

REFERENCES = [
    ("sqlalchemy_vectors", "sqlalchemy_queue_pool.py"),
    ("generic_pool_vectors", "generic_pool.mjs"),
]


def record(script, python, node):
    if script.endswith(".py"):
        command = [python, str(REFERENCE / script)]
    else:
        command = [node, str(REFERENCE / script)]
    done = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    if done.returncode != 0:
        raise SystemExit(f"{script} failed:\n{done.stderr.strip()}")
    return json.loads(done.stdout)


def span(ms):
    return "@moondate.Span::new()" if ms == 0 else f"@moondate.Span::new(millis={ms}L)"


def steps_of(scenario):
    lines = []
    for step in scenario["steps"]:
        # The plans count milliseconds; a pool's clock is nanoseconds.
        at = "{:,}L".format(step["at"] * 1_000_000).replace(",", "_")
        if step["op"] == "take":
            lines.append(f"      Take({at}),")
        elif step["op"] == "give":
            lines.append(f"      Give({at}, {step['of']}),")
        elif step["op"] == "drop":
            lines.append(f"      Drop({at}, {step['of']}),")
        else:
            lines.append(f"      Pause({at}),")
    return lines


def scenarios_of(name, recording):
    out = [f"///|", f"let {name} : Array[Vector] = ["]
    for scenario in recording["scenarios"]:
        out.append("  {")
        out.append(f'    name: "{scenario["name"]}",')
        out.append("    limits: {")
        out.append(f'      size: {scenario["size"]},')
        out.append(f'      idle: {scenario["idle"]},')
        out.append(f'      keep: {span(scenario["keep_ms"])},')
        out.append(f'      life: {span(scenario["life_ms"])},')
        out.append("    },")
        out.append("    steps: [")
        out.extend(steps_of(scenario))
        out.append("    ],")
        out.append("    takes: [" + ", ".join(str(t) for t in scenario["takes"]) + "],")
        out.append(
            "    gauges: ["
            + ", ".join(f"({idle}, {live})" for idle, live in scenario["gauges"])
            + "],"
        )
        out.append("  },")
    out.append("]")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--python", default=sys.executable)
    ap.add_argument("--node", default="node")
    ap.add_argument("--moon", default="moon")
    args = ap.parse_args()

    recordings = [
        (name, record(script, args.python, args.node)) for name, script in REFERENCES
    ]
    sources = [recording["source"] for _, recording in recordings]
    body = [
        "// Generated by `scripts/gen_reference_vectors.py`; do not edit.",
        "//",
        "// Each vector is what a mature pool of another language answered when the",
        "// steps in `scripts/reference/*_plan.json` were run against it. The",
        "// references are " + " and ".join(sources) + ".",
        "// `reference_wbtest.mbt` replays the same steps against moonpool and compares.",
        "",
    ]
    for name, recording in recordings:
        body.extend(scenarios_of(name, recording))
        body.append("")
    OUT.write_text("\n".join(body), encoding="utf-8", newline="\n")
    subprocess.run([args.moon, "fmt"], cwd=ROOT, capture_output=True)
    print(f"{OUT.relative_to(ROOT).as_posix()}: {', '.join(sources)}")


if __name__ == "__main__":
    main()
